"""Generate the edit-time style factory from the approved pilot geometry."""
from pathlib import Path
import importlib.util
import json
import re
import xml.etree.ElementTree as ET

ROOT=Path(__file__).resolve().parents[1]
spec=importlib.util.spec_from_file_location('pilot',ROOT/'tools/build-style-pilot.py')
pilot=importlib.util.module_from_spec(spec)
spec.loader.exec_module(pilot)
variants=[
    ('Town_A',30,30,2,'M05',False),('Town_B',34,29,2,'M05',False),
    ('Town_Workshop',29,22,2,'M05',True),
    ('Cottage_A',26,28,1,'M06',False),('Cottage_B',29,25,1,'M05',False),
    ('Cottage_Porch',25,21,1,'M06',True),
    ('Barn',48,36,1,'M06',False),('TownHall',58,45,2,'M05',False),
    ('Windmill',18,16,2,'M06',False),
]
catalog={}
for name,w,d,floors,mat,canopy in variants:
    holder=ET.Element('roblox')
    model=pilot.house(holder,name,(0,0,0),w,d,floors,mat,canopy=canopy)
    parts=[]
    for node in model.findall('Item'):
        p=node.find('Properties')
        n=p.find("string[@name='Name']").text
        size=[float(v.text) for v in p.find("Vector3[@name='size']")]
        cf=[float(v.text) for v in p.find("CoordinateFrame[@name='CFrame']")]
        color=int(p.find("Color3uint8[@name='Color3uint8']").text)&0xFFFFFF
        mid=n[:3]
        if name=='Barn' and mid=='M01': mid='M03'; color=int(pilot.MATS[mid]['hex'][1:],16)
        parts.append([n,node.get('class'),size,cf,mid,color,
                      p.find("bool[@name='CanCollide']").text=='true',
                      p.find("bool[@name='CastShadow']").text=='true'])
    catalog[name]={'width':w,'depth':d,'parts':parts}
materials={m['id']:[m['pilotMaterial'],int(m['hex'][1:],16)] for m in pilot.SPEC['materials']}
runtime=(ROOT/'tools/world-style-runtime.luau').read_text(encoding='utf-8')
header='-- Generated by tools/package-world-style.py; edit-time only. No runtime loops.\n'
header+='local CATALOG = game:GetService("HttpService"):JSONDecode([==['+json.dumps(catalog,separators=(',',':'))+']==])\n'
header+='local MATERIALS = game:GetService("HttpService"):JSONDecode([==['+json.dumps(materials,separators=(',',':'))+']==])\n'
source=header+runtime
target=ROOT/'src/world/MedievalStyle.luau'
target.parent.mkdir(exist_ok=True)
target.write_text(source,encoding='utf-8')
body=(ROOT/'tools/apply-style-main-body.luau').read_text(encoding='utf-8')
(ROOT/'apply-style-main.luau').write_text('-- Generated edit-time migration; back up the place first.\nlocal Style=(function()\n'+source+'\nend)()\n'+body,encoding='utf-8')
# Preserve the existing map generator, replacing only its old house function.
build=ROOT/'build-map.luau'
text=build.read_text(encoding='utf-8')
start='-- BEGIN GENERATED MEDIEVAL STYLE A\n'
end='-- END GENERATED MEDIEVAL STYLE A\n'
wrapper='''local Style = (function()
SOURCE
end)()
local function house(parent,name,pos,w,d,roofColor,angle,height)
    return Style.place(parent,name,CFrame.new(pos)*CFrame.Angles(0,angle or 0,0),w+1,d+1)
end
'''.replace('SOURCE',source)
if start in text:
    text=text[:text.index(start)]+start+wrapper+end+text[text.index(end)+len(end):]
else:
    a=text.index('local function house(parent,name,pos,w,d,roofColor,angle,height)')
    b=text.index('local function fence(parent,a,b)',a)
    text=text[:a]+start+wrapper+end+text[b:]
# Keep the terrain palette coherent on future rebuilds too.
text=text.replace('Color3.fromRGB(100,118,64)','Color3.fromRGB(116,128,90)')
text=text.replace('Color3.fromRGB(121,104,75)','Color3.fromRGB(137,116,84)')
text=text.replace('Color3.fromRGB(127,127,114)','Color3.fromRGB(132,130,121)')
text=text.replace('Color3.fromRGB(83,62,43)','Color3.fromRGB(85,68,56)')
text=text.replace('Color3.fromRGB(191,177,143)','Color3.fromRGB(206,193,165)')
text=text.replace('Color3.fromRGB(125,108,79)','Color3.fromRGB(137,116,84)')
tree_call='                Style.optimizeTree(model)\n                treeCount+=1'
if tree_call not in text:
    text=text.replace('                treeCount+=1',tree_call)
windmill_start=text.index('-- Windmill landmark;')
windmill_end=text.index('print("MAP_BUILD_PHASE","Forests")',windmill_start)
text=text[:windmill_start]+'''-- Windmill landmark; static style A scenery.
local mill=settlements.Millbridge
local millAt=east+Vector3.new(-145,0,90)
local windmill=Style.place(mill,"Windmill",CFrame.new(millAt),21,24)
Style.addWindmillSails(windmill,CFrame.new(millAt))
'''+text[windmill_end:]
cleanup='Style.releaseTemplates()\n'
if cleanup not in text:
    text=text.replace('map:SetAttribute("HillCount",hillCount)',cleanup+'map:SetAttribute("HillCount",hillCount)')
build.write_text(text,encoding='utf-8')
print(f'Generated {len(catalog)} variants; factory {len(source)} characters')
