"""Build a self-contained Command Bar installer for the medieval combat system.

Reads src/combat/<Service>/... and writes install-combat.luau at the repository root.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src" / "combat"
TARGET = ROOT / "install-combat.luau"
BUILD_ID = 1


def quote(text: str) -> str:
    level = 0
    while "]" + "=" * level + "]" in text:
        level += 1
    return "[" + "=" * level + "[" + text + "]" + "=" * level + "]"


def classify(name: str):
    if name.endswith(".server.luau"):
        return name.removesuffix(".server.luau"), "Script"
    if name.endswith(".client.luau"):
        return name.removesuffix(".client.luau"), "LocalScript"
    return name.removesuffix(".luau"), "ModuleScript"


lines = [
    "-- Generated by tools/package-combat.py. Run in the Studio Command Bar with Play stopped.",
    'assert(not game:GetService("RunService"):IsRunning(),"Stop Play first")',
    'local editor=game:GetService("ScriptEditorService")',
    """local function ensure(parent,name,class)
local o=parent:FindFirstChild(name)
if o then assert(o.ClassName==class,"Class mismatch: "..o:GetFullName()) return o end
local n=Instance.new(class) n.Name=name n.Parent=parent return n end""",
    'local ServerScriptService=game:GetService("ServerScriptService")',
    'local ReplicatedStorage=game:GetService("ReplicatedStorage")',
    'local StarterPlayerScripts=game:GetService("StarterPlayer"):WaitForChild("StarterPlayerScripts")',
    "-- remove the previous install so no stale script survives",
    """for _,o in {ServerScriptService:FindFirstChild("CombatBootstrap"),ServerScriptService:FindFirstChild("Combat"),StarterPlayerScripts:FindFirstChild("CombatClient"),ReplicatedStorage:FindFirstChild("CombatConfig"),ReplicatedStorage:FindFirstChild("CombatNet"),ReplicatedStorage:FindFirstChild("CombatRemotes")} do
if o then o:Destroy() end end""",
]

SERVICES = {
    "ReplicatedStorage": "ReplicatedStorage",
    "ServerScriptService": "ServerScriptService",
    "StarterPlayer": "StarterPlayerScripts",
}

manifest = []
for path in sorted(SRC.rglob("*.luau")):
    relative = path.relative_to(SRC)
    parts = list(relative.parts)
    service = parts[0]
    if service not in SERVICES:
        raise SystemExit(f"Unsupported service folder: {service}")
    name, klass = classify(parts[-1])
    parent_expr = SERVICES[service]
    folders = parts[1:-1]
    if service == "StarterPlayer" and folders and folders[0] == "StarterPlayerScripts":
        folders = folders[1:]
    lines.append("do")
    lines.append(f"local parent={parent_expr}")
    for folder in folders:
        lines.append("parent=ensure(parent," + json.dumps(folder) + ',"Folder")')
    lines.append("local obj=ensure(parent," + json.dumps(name) + "," + json.dumps(klass) + ")")
    if klass in ("Script", "LocalScript"):
        lines.append("obj.Enabled=false")
    lines.append("local source=" + quote(path.read_text(encoding="utf-8")))
    lines.append("editor:UpdateSourceAsync(obj,function() return source end)")
    if klass in ("Script", "LocalScript"):
        lines.append("obj.Enabled=true")
    lines.append("end")
    manifest.append({"file": str(relative), "path": "/".join(parts[:-1] + [name]), "class": klass})

lines.append('print("COMBAT_INSTALL_OK",' + str(len(manifest)) + ',"source files")')
lines.append("do")
lines.append('local config=ReplicatedStorage:FindFirstChild("CombatConfig")')
lines.append("if config then config:SetAttribute(\"InstalledBuild\"," + str(BUILD_ID) + ") end")
lines.append("end")
TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8")
(ROOT / "docs").mkdir(exist_ok=True)
(ROOT / "docs" / "combat-manifest.json").write_text(
    json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
)
print(f"Packaged {len(manifest)} sources; installer {TARGET.stat().st_size} bytes")
